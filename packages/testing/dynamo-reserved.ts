export const RESERVED: ReadonlySet<string> = new Set(WORDS.split(/\s+/).filter(Boolean));

/** Expression grammar words and functions: these are the syntax, not names. */
const SYNTAX = new Set(['AND', 'OR', 'NOT', 'BETWEEN', 'IN', 'SET', 'REMOVE', 'ADD', 'DELETE']);
const FUNCTIONS = new Set([
  'attribute_exists',
  'attribute_not_exists',
  'attribute_type',
  'begins_with',
  'contains',
  'size',
  'if_not_exists',
  'list_append'
]);

/** The bare (unaliased) names in an expression that DynamoDB would refuse. */
export function bareReserved(expression: string): string[] {
  const found: string[] = [];
  for (const match of expression.matchAll(/[#:]?[A-Za-z_]\w*/g)) {
    const word = match[0];
    if (word.startsWith('#') || word.startsWith(':')) continue;
    if (
      FUNCTIONS.has(word) &&
      expression
        .slice(match.index + word.length)
        .trimStart()
        .startsWith('(')
    )
      continue;
    const upper = word.toUpperCase();
    if (SYNTAX.has(upper)) continue;
    if (RESERVED.has(upper)) found.push(word);
  }
  return found;
}
