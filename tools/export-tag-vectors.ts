/** Writes contracts/tag-vectors.json: how Release Notes reads tags, from the
 * server's own rules (packages/domain/tags.ts), for every client to check
 * itself against. Run it after a change to those rules; a test fails until it
 * is. */
import { writeFileSync } from 'node:fs';
import { spelling, textTags, tagKey } from '../packages/domain/tags.ts';
const Z = String.fromCodePoint(0x200d),
  V = String.fromCodePoint(0xfe0f),
  N = String.fromCodePoint(0x200c);
const names = [
  'Road Trip',
  'road trip',
  'road-trip',
  'Road_Trip',
  'ROAD   TRIP',
  '#Road Trip',
  '## road trip',
  '  Lake   house ',
  'Café',
  'Mañana',
  'İstanbul',
  'Straße',
  'Maine 2016',
  'maine-2016',
  '2016',
  'Москва',
  '東京',
  '東京 旅行',
  'שלום',
  'नमस्ते',
  'می' + N + 'خواهم',
  'café-東京',
  'Tokyo東京',
  'Kyoto 京都',
  '🚗',
  'Road Trip 🚗',
  '🚗 Road Trip',
  '🏖' + V + ' Beach',
  '🏖 beach',
  '👍🏽',
  '👨' + Z + '👩' + Z + '👧 family',
  '🇳🇴 trip',
  'x'.repeat(50)
];
const refused = [
  ['a,b', 'comma'],
  ['a，b', 'comma'],
  ['two\nlines', 'break'],
  ['tab\u0007bell', 'break'],
  ['x'.repeat(51), 'long'],
  ['#', 'empty'],
  ['   ', 'empty'],
  ['---', 'empty'],
  ['!?', 'empty']
];
const texts = [
  'At the #Lake with #café-東京, then #lake again and #Maine-2016',
  'PR #31 and #2016 are no tags; #東京 and #Москва are',
  'Two words #Road Trip make one hashtag: #Road'
];
const out = {
  about:
    "How Release Notes reads tags (docs/TAGS.md). Every client checks itself against these: a name as typed, its name as kept and its key; what a tags field refuses; and the tags a note text's hashtags make. Generated by the server's rules and pinned by its tests.",
  names: names.map((typed) => {
    const t = spelling(typed);
    if (typeof t === 'string') throw new Error(typed + ' ' + t);
    return { typed, name: t.name, key: t.key };
  }),
  refused: refused.map(([typed, reason]) => {
    const t = spelling(typed);
    if (t !== reason) throw new Error(`${typed}: ${JSON.stringify(t)}`);
    return { typed, reason };
  }),
  text: texts.map((text) => ({ text, tags: textTags(text) })),
  keys_are_stable: names.map((n) => tagKey(n)).every((k) => tagKey(k) === k)
};
writeFileSync(new URL('../contracts/tag-vectors.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
if (!process.argv.includes('--quiet'))
  console.log(`${out.names.length} names, ${out.refused.length} refusals, ${out.text.length} texts`);
